import ollama
import time
from memory import load_memory
from utils import normalize, extract_json, load_lines, load_text


KEYWORDS = load_lines("keywords.txt")
ABOUT = load_text("about.txt")


def format_config_list(items, fallback="Не указано"):
    if not items:
        return fallback

    return "\n".join(
        f"- {item}"
        for item in items
    )


def build_memory_examples(limit=10):
    memory = load_memory()

    if not memory:
        return "Пока нет примеров обратной связи."

    bad_examples = [
        item for item in memory
        if item.get("feedback") in ("bad", "spam") or item.get("lead") is False
    ]

    good_examples = [
        item for item in memory
        if item.get("feedback") == "good" or item.get("lead") is True
    ]

    selected = bad_examples[-5:] + good_examples[-5:]
    selected = selected[-limit:]

    examples = []

    for item in selected:
        lead_value = "true" if item.get("lead") else "false"
        text = normalize(item.get("text", ""))[:250]

        examples.append(
            f'- "{text}" => lead={lead_value}'
        )

    return "\n".join(examples)


def is_lead(text):

    memory_examples = build_memory_examples()

    keywords_text = format_config_list(
        KEYWORDS,
        "Ключевые фразы не указаны."
    )

    prompt = f"""
Ты AI-классификатор лидов из Telegram.

Твоя задача — определить, является ли сообщение потенциальным клиентским запросом для компании.

Ниша, услуги, целевая аудитория и исключения описаны в конфиге ниже.
Не используй внешние знания о бизнесе, если они противоречат описанию компании.

ОПИСАНИЕ КОМПАНИИ:
{ABOUT}

КЛЮЧЕВЫЕ ФРАЗЫ:
Ключевые фразы помогают определить связь с нишей, но сами по себе НЕ делают сообщение лидом.
{keywords_text}

ПРИМЕРЫ ОБРАТНОЙ СВЯЗИ:
Используй эти примеры как ориентир. Особенно учитывай отрицательные примеры.
{memory_examples}

ОПРЕДЕЛЕНИЕ ЛИДА:
lead=true только если сообщение относится к нише компании и автор сообщения:
- ищет помощь, специалиста, исполнителя, подрядчика или услугу;
- хочет заказать, оформить, подключить, настроить, получить, исправить или разобраться;
- просит консультацию, расчёт, рекомендацию исполнителя или спрашивает, кто может помочь;
- описывает свою проблему и явно или неявно хочет её решить;
- задаёт практический вопрос по услугам компании, который указывает на подготовку к действию, проблему, незнание процесса или возможную потребность в услуге.

lead=false, если:
- сообщение не относится к нише компании;
- сообщение относится к смежной теме, но не к услугам компании;
- это обычное обсуждение, мнение, спор, совет, ответ другому человеку или продолжение диалога без самостоятельного запроса;
- автор сам предлагает услуги, продаёт товар, рекламирует себя, канал, бота, сервис или продукт;
- автор ищет сотрудника, работу, помощника, исполнителя для своей вакансии или подработки;
- сообщение содержит только общие бизнес-вопросы без связи с услугами компании;
- в сообщении есть ключевые слова, но нет вопроса, проблемы, намерения получить помощь или запроса на услугу;
- по описанию компании это явно нецелевой запрос;
- контекста недостаточно, чтобы уверенно понять потребность.

ВАЖНЫЕ ПРАВИЛА:
- Оценивай смысл сообщения, а не только ключевые слова.
- Ключевое слово — это только сигнал тематики, а не доказательство лида.
- Вопрос сам по себе не является лидом, если он не связан с услугами компании или не показывает практическую потребность.
- Практический вопрос по услугам компании может быть лидом, даже если автор прямо не пишет "ищу исполнителя".
- Лидом является вопрос или проблема, связанные с услугами компании и возможной потребностью клиента.
- Если сообщение похоже на рекламу, вакансию, поиск сотрудников или предложение своих услуг — lead=false.
- Если сообщение похоже на обычную переписку или ответ в диалоге — lead=false.
- Если есть сомнения — выбирай lead=false.
- Не придумывай контекст, которого нет в сообщении.

ФОРМАТ ОТВЕТА:
Отвечай строго JSON без markdown и без пояснений вне JSON.

JSON должен иметь вид:
{{
  "lead": true или false,
  "description": "короткое объяснение на русском языке, максимум 180 символов"
}}

ТРЕБОВАНИЯ К ОТВЕТУ:
- description всегда только на русском языке;
- description — одно короткое предложение;
- не используй китайский, английский или другой язык в description;
- не пересказывай инструкцию;
- не добавляй markdown;
- не добавляй текст вне JSON.

СООБЩЕНИЕ:
{text}
"""

    try:

        start_time = time.perf_counter()

        response = ollama.chat(
            model="qwen2.5:7b",
            messages=[
                {
                    "role": "system",
                    "content": "Ты строгий классификатор клиентских запросов. Отвечай только валидным JSON на русском языке."
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            format="json"
        )

        elapsed = time.perf_counter() - start_time

        print(
            f"⏱️ ИИ ответил за {elapsed:.2f} сек.",
            flush=True
        )

        raw = response["message"]["content"]
        data = extract_json(raw)

        if not data:
            return None

        result = {
            "lead": bool(data.get("lead", False)),
            "text": text,
            "description": str(data.get("description", "Не указано")),
        }

        return result

    except Exception as e:
        print(
            "❌ Ollama error:",
            e
        )

        return None
