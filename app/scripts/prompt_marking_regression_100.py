def get_niche_by_id(niche_id: int) -> NicheWithConfig:
    niches = get_active_niches_with_config()

    for niche in niches:
        if int(niche["id"]) == niche_id:
            return niche

    raise RuntimeError(
        f"Активная ниша с id={niche_id} не найдена"
    )


